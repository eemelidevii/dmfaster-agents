#!/usr/bin/env node

import { spawnSync } from "node:child_process";
import { createRequire } from "node:module";
import { mkdtempSync, readFileSync, rmSync, writeFileSync, mkdirSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { build } from "esbuild";

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const temporaryDirectory = mkdtempSync(path.join(tmpdir(), "dmfaster-mcp-ui-"));
const javascriptPath = path.join(temporaryDirectory, "campaign-workspace.js");
const cssPath = path.join(temporaryDirectory, "campaign-workspace.css");
const generatedPath = path.join(packageRoot, "src", "campaign-workspace-assets.generated.ts");
const require = createRequire(import.meta.url);

function writeWhenChanged(target, content) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {
    // The first generation creates the file.
  }
  if (current !== content) writeFileSync(target, content, "utf8");
}

try {
  await build({
    entryPoints: [path.join(packageRoot, "ui", "app.tsx")],
    outfile: javascriptPath,
    bundle: true,
    minify: true,
    format: "iife",
    platform: "browser",
    target: ["es2022"],
    jsx: "automatic",
    define: {
      "process.env.NODE_ENV": JSON.stringify("production"),
    },
    legalComments: "none",
  });

  const tailwindCli = path.join(path.dirname(require.resolve("@tailwindcss/cli/package.json")), "dist", "index.mjs");
  const cssResult = spawnSync(process.execPath, [
    tailwindCli,
    "-i",
    path.join(packageRoot, "ui", "styles.css"),
    "-o",
    cssPath,
    "--minify",
  ], {
    cwd: packageRoot,
    encoding: "utf8",
  });
  if (cssResult.status !== 0) {
    throw new Error(cssResult.stderr.trim() || cssResult.stdout.trim() || "Tailwind failed to build the MCP App stylesheet.");
  }

  const javascript = readFileSync(javascriptPath, "utf8").replaceAll("</script", "<\\/script");
  const css = readFileSync(cssPath, "utf8").replaceAll("</style", "<\\/style");
  const generated = [
    "// Generated by tools/build-campaign-workspace-ui.mjs. Do not edit by hand.",
    `export const CAMPAIGN_WORKSPACE_APP_JAVASCRIPT = ${JSON.stringify(javascript)};`,
    `export const CAMPAIGN_WORKSPACE_APP_CSS = ${JSON.stringify(css)};`,
    "",
  ].join("\n");
  mkdirSync(path.dirname(generatedPath), { recursive: true });
  writeWhenChanged(generatedPath, generated);
} finally {
  const expectedPrefix = path.join(tmpdir(), "dmfaster-mcp-ui-");
  if (!temporaryDirectory.startsWith(expectedPrefix)) {
    throw new Error(`Refusing to remove unexpected temporary directory: ${temporaryDirectory}`);
  }
  rmSync(temporaryDirectory, { recursive: true, force: true });
}
